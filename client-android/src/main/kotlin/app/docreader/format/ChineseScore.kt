    fun score(text: String): Int = text.sumOf { char -> when {
        char in common -> 8
        char.code in 0xe000..0xf8ff -> -20
        char in '\u4e00'..'\u9fff' -> 1
        char in "，。；：「」、“”！？《》（）" -> 5
        char == '\uFFFD' -> -50
        char.isISOControl() && char !in "\n\r\t" -> -30
        else -> 0
    } }
